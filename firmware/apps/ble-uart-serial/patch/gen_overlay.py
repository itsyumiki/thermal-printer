"""Regenerate overlay/ of the ble-uart-serial app from the PRISTINE vendor SDK.

    gen_overlay.py <pristine SDK dir> [app dir]

The overlay files are whole replacements of SDK files (that is how scripts/apply_app.py
works), so they are generated by exact-string edits of the pristine file instead of being
edited by hand: every edit must match exactly once, or this script fails. Re-run it (and
`git diff`) after changing the SDK pin. The unified diffs of what it does are committed
next to it in patch/*.diff.

Edited SDK files (relative to the SDK root):
  apps/spp_and_le/examples/trans_data/ble_trans.c       BLE <-> bridge glue
  apps/spp_and_le/examples/trans_data/ble_trans_profile.h  ae01: also allow WRITE (with response)
  apps/spp_and_le/include/app_config.h                  LIB_DEBUG 1 (library logs on)
"""
import difflib
import re
import sys
from pathlib import Path

SDK = Path(sys.argv[1]).resolve()
APP = Path(sys.argv[2]).resolve() if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent
OUT = APP / "overlay"
DIFFS = APP / "patch"


def rep(text, old, new, what):
    n = text.count(old)
    if n != 1:
        sys.exit(f"gen_overlay: {what}: expected exactly 1 match, found {n}")
    return text.replace(old, new)


def rep_re(text, pattern, new, what):
    ms = list(re.finditer(pattern, text, re.S))
    if len(ms) != 1:
        sys.exit(f"gen_overlay: {what}: expected exactly 1 regex match, found {len(ms)}")
    m = ms[0]
    return text[: m.start()] + new + text[m.end():]


def write(rel, text, orig):
    dst = OUT / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(text, encoding="utf-8", newline="")
    d = "".join(difflib.unified_diff(orig.splitlines(True), text.splitlines(True),
                                     f"a/{rel}", f"b/{rel}"))
    (DIFFS / (Path(rel).name + ".diff")).write_text(d, encoding="utf-8")
    print(f"wrote overlay/{rel} ({len(d.splitlines())} diff lines)")


def read(rel):
    return (SDK / rel).read_text(encoding="utf-8", newline="")


