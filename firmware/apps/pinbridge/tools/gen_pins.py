#!/usr/bin/env python3
"""gen_pins.py -- turn a pinbridge pin config (pins.toml) into the C header, the Python module
and a markdown table, and compute the 32-bit config hash that `HEL` returns.

    gen_pins.py <pins.toml> [--c OUT.h] [--py OUT.py] [--md OUT.md] [--hash]

Outputs are deterministic (no timestamps), so `scripts/check-pinbridge.sh` can regenerate and diff
them against the committed copies.

Config hash (design doc section 4): FNV-1a 32 bit over a canonical text, one line per allowed pin in
(port, bit) order:   "<NAME> <caps> <adc|-> <pwm|->\\n"   with caps joined by ',' in the fixed order
in,out,pu,pd,adc,pwm. Aliases, notes and the denied list are NOT part of the hash.
"""
import argparse
import re
import sys
import tomllib
from pathlib import Path

CAP_ORDER = ["in", "out", "pu", "pd", "adc", "pwm"]
PIN_RE = re.compile(r"^P([A-D])(\d{1,2})$")
PORT_BITS = {"A": 16, "B": 16, "C": 16, "D": 8}
SPECIAL_DENIED = {"DP", "DM"}


def fail(msg):
    sys.exit(f"gen_pins: {msg}")


def fnv1a32(data: bytes) -> int:
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def parse_pin(name):
    m = PIN_RE.match(name)
    if not m or name != f"P{m.group(1)}{int(m.group(2))}":
        return None
    port, bit = m.group(1), int(m.group(2))
    if bit >= PORT_BITS[port]:
        return None
    return "ABCD".index(port), bit


def load(path):
    cfg = tomllib.loads(Path(path).read_text(encoding="utf-8"))
    if cfg.get("schema") != 1:
        fail(f"{path}: schema must be 1")
    max_pins = cfg.get("max_pins", 12)
    pins = []
    for name, p in cfg.get("pins", {}).items():
        pb = parse_pin(name)
        if pb is None:
            fail(f"{path}: bad pin name {name!r} (want PA0..PD7 style, no zero padding)")
        caps = p.get("caps", [])
        bad = [c for c in caps if c not in CAP_ORDER]
        if bad or len(set(caps)) != len(caps) or not caps:
            fail(f"{path}: {name}: bad caps {caps!r}")
        if ("adc" in caps) != ("adc" in p):
            fail(f"{path}: {name}: caps 'adc' and an `adc = <channel>` value must go together")
        if ("pwm" in caps) != ("pwm" in p):
            fail(f"{path}: {name}: caps 'pwm' and a `pwm = \"<note>\"` value must go together")
        if "adc" in p and not (isinstance(p["adc"], int) and 0 <= p["adc"] <= 0xF):
            fail(f"{path}: {name}: adc must be an AD_CH number 0..15")
        alias = p.get("alias")
        if alias is not None and not re.fullmatch(r"[a-z][a-z0-9_]*", alias):
            fail(f"{path}: {name}: alias must be lower-case [a-z][a-z0-9_]*")
        pins.append({
            "name": name, "port": pb[0], "bit": pb[1],
            "caps": [c for c in CAP_ORDER if c in caps],
            "adc": p.get("adc"), "pwm": p.get("pwm"),
            "alias": alias, "note": p.get("note", ""),
        })
    pins.sort(key=lambda p: (p["port"], p["bit"]))
    if not pins:
        fail(f"{path}: no pins")
    if len(pins) > max_pins:
        fail(f"{path}: {len(pins)} pins but max_pins = {max_pins} (replies must fit 128 bytes)")
    aliases = [p["alias"] for p in pins if p["alias"]]
    if len(set(aliases)) != len(aliases):
        fail(f"{path}: duplicate alias")
    denied = dict(cfg.get("denied", {}))
    for name in denied:
        if name not in SPECIAL_DENIED and parse_pin(name) is None:
            fail(f"{path}: denied entry {name!r} is not a pin name")
    both = sorted(set(denied) & {p["name"] for p in pins})
    if both:
        fail(f"{path}: pin(s) both allowed and denied: {both}")
    return pins, denied


def canonical(pins):
    out = []
    for p in pins:
        adc = "-" if p["adc"] is None else str(p["adc"])
        pwm = "-" if p["pwm"] is None else p["pwm"]
        out.append(f"{p['name']} {','.join(p['caps'])} {adc} {pwm}\n")
    return "".join(out)


def config_hash(pins):
    return fnv1a32(canonical(pins).encode("utf-8"))


def sort_key_denied(name):
    pb = parse_pin(name)
    return (0, pb) if pb else (1, (0, 0))


def gen_c(pins, h, src):
    lines = [
        f"/* GENERATED by firmware/apps/pinbridge/tools/gen_pins.py from {src} -- DO NOT EDIT.",
        " * Regenerate with scripts/check-pinbridge.sh --update; scripts/check-pinbridge.sh diffs. */",
        "#ifndef PB_PINS_H",
        "#define PB_PINS_H",
        "",
        f"#define PB_NPINS        {len(pins)}",
        f"#define PB_CFG_HASH     0x{h:08x}u",
        f'#define PB_CFG_HASH_STR "{h:08x}"',
        "",
        "/* X(name, port(0=A..3=D), bit, caps, adc_channel or PB_NOADC, pwm_present 0/1)",
        " * Needs PB_CAP_* and PB_NOADC defined by the includer (pb_core.h does). */",
        "#define PB_PIN_LIST(X) \\",
    ]
    for i, p in enumerate(pins):
        caps = "|".join("PB_CAP_" + c.upper() for c in p["caps"])
        adc = "PB_NOADC" if p["adc"] is None else str(p["adc"])
        pwm = 0 if p["pwm"] is None else 1
        end = " \\" if i + 1 < len(pins) else ""
        lines.append(f'    X("{p["name"]}", {p["port"]}, {p["bit"]}, {caps}, {adc}, {pwm}){end}')
    lines += ["", "#endif /* PB_PINS_H */", ""]
    return "\n".join(lines)


def py_str(s):
    return repr(s)


def gen_py(pins, denied, h, src):
    out = [
        f'"""GENERATED by firmware/apps/pinbridge/tools/gen_pins.py from {src} -- DO NOT EDIT.',
        "",
        "Same table as the firmware's pb_pins.h. Regenerate with scripts/check-pinbridge.sh --update.",
        '"""',
        "",
        f'CFG_HASH = "{h:08x}"',
        "",
        "# (name, port, bit, caps, adc_channel, pwm_note, alias, note)",
        "PINS = (",
    ]
    for p in pins:
        out.append("    (%s, %d, %d, %s, %r, %r, %r, %s)," % (
            py_str(p["name"]), p["port"], p["bit"], tuple(p["caps"]), p["adc"], p["pwm"],
            p["alias"], py_str(p["note"])))
    out += [")", "", "# pins that are deliberately not available, with the reason (documentation only)", "DENIED = {"]
    for name in sorted(denied, key=sort_key_denied):
        out.append(f"    {py_str(name)}: {py_str(denied[name])},")
    out += ["}", ""]
    return "\n".join(out)


def gen_md(pins, denied, h):
    o = [f"<!-- GENERATED by gen_pins.py -- DO NOT EDIT. -->", "",
         f"Config hash: `{h:08x}` (what `HEL` returns).", "",
         "| Pin | Allowed modes | ADC | Alias | Note |", "|---|---|---|---|---|"]
    modes = {"in": "in", "out": "lo hi", "pu": "up", "pd": "dn", "adc": "adc", "pwm": "pwm"}
    for p in pins:
        m = ["hiz"] + [modes[c] for c in p["caps"]]
        adc = "" if p["adc"] is None else f"ch {p['adc']}"
        o.append(f"| {p['name']} | {' '.join(m)} | {adc} | {p['alias'] or ''} | {p['note']} |")
    o += ["", "Denied pins (answer `err pin`):", "", "| Pin | Why |", "|---|---|"]
    for name in sorted(denied, key=sort_key_denied):
        o.append(f"| {name} | {denied[name]} |")
    o += ["| everything else | not confirmed as bonded out on the QFN32 package (no complete package pinout on the build box) |", ""]
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("toml")
    ap.add_argument("--c")
    ap.add_argument("--py")
    ap.add_argument("--md")
    ap.add_argument("--hash", action="store_true")
    a = ap.parse_args()
    pins, denied = load(a.toml)
    h = config_hash(pins)
    src = Path(a.toml).name
    if a.c:
        Path(a.c).write_text(gen_c(pins, h, src), encoding="utf-8")
    if a.py:
        Path(a.py).write_text(gen_py(pins, denied, h, src), encoding="utf-8")
    if a.md:
        Path(a.md).write_text(gen_md(pins, denied, h), encoding="utf-8")
    if a.hash or not (a.c or a.py or a.md):
        print(f"{h:08x}")


if __name__ == "__main__":
    main()
