#!/usr/bin/env python3
"""Generate the host TypeScript thermistor table from the firmware's stock table."""
import pathlib
import re
import sys


def generate(source: pathlib.Path) -> str:
    text = source.read_text(encoding="utf-8")
    n_match = re.search(r"#define\s+PB_THERM_TABLE_N\s+(\d+)u", text)
    table_match = re.search(
        r"static\s+const\s+uint32_t\s+pb_therm_table\[PB_THERM_TABLE_N\]\s*=\s*\{(.*?)\};",
        text,
        re.S,
    )
    if not n_match or not table_match:
        raise SystemExit(f"could not parse thermistor table in {source}")
    expected = int(n_match.group(1))
    values = [int(value) for value in re.findall(r"(\d+)u", table_match.group(1))]
    if len(values) != expected:
        raise SystemExit(f"expected {expected} thermistor values, found {len(values)}")
    if any(a <= b for a, b in zip(values, values[1:])):
        raise SystemExit("thermistor table must be strictly descending")
    rows = [
        "/* Generated by firmware/apps/pinbridge/tools/gen_thermistor.py; do not edit. */",
        "export const THERMISTOR_TABLE_OHMS: readonly number[] = [",
    ]
    rows.extend(f"  {value}," for value in values)
    rows.extend(["] as const;", ""])
    return "\n".join(rows)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: gen_thermistor.py SOURCE_HEADER OUTPUT_TS")
    pathlib.Path(sys.argv[2]).write_text(generate(pathlib.Path(sys.argv[1])), encoding="utf-8")
